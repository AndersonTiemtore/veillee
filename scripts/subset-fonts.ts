/**
 * Builds src/fonts/GentiumBook-*.woff2 from the SIL release (OFL).
 *
 * Google Fonts' Gentium Book Plus lacks ɛ ɩ ʋ ɓ ɗ ɲ even in its latin-ext
 * subset, so headings would fall back for national-language names. The SIL
 * build has them; we keep Latin, Latin extended, IPA, combining marks and
 * Latin Extended Additional (ẽ), then compress to WOFF2.
 *
 * Usage: tsx scripts/subset-fonts.ts <dir containing GentiumBook-*.ttf>
 * Source: https://github.com/silnrsi/font-gentium/releases (GentiumBook-7.000.zip)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import subsetFont from "subset-font";

type Range = [number, number];

/**
 * Two files per weight, declared with matching `unicode-range` in
 * src/styles/fonts.css: browsers only download "ext" when a page actually
 * contains national-language characters.
 */
const SUBSETS: Record<string, Range[]> = {
  latin: [
    [0x20, 0x7e],
    [0xa0, 0xff],
    [0x152, 0x153], // œ Œ
    [0x2000, 0x206f], // Punctuation
    [0x20ac, 0x20ac],
    [0x2122, 0x2122],
  ],
  ext: [
    [0x100, 0x151],
    [0x154, 0x24f], // Latin Extended-A/B (ƴ, ĩ, ũ…)
    [0x250, 0x2af], // IPA Extensions (ɛ ɩ ʋ ɓ ɗ ŋ ɲ)
    [0x2b0, 0x2ff], // Spacing modifiers
    [0x300, 0x36f], // Combining diacritics (tones, nasalisation)
    [0x1e00, 0x1eff], // Latin Extended Additional (ẽ)
  ],
};

const toText = (ranges: Range[]) =>
  ranges
    .flatMap(([from, to]) =>
      Array.from({ length: to - from + 1 }, (_, i) => String.fromCodePoint(from + i)),
    )
    .join("");

const toUnicodeRange = (ranges: Range[]) =>
  ranges
    .map(([a, b]) => (a === b ? `U+${hex(a)}` : `U+${hex(a)}-${hex(b)}`))
    .join(", ");
const hex = (n: number) => n.toString(16).toUpperCase();

async function main() {
  const src = process.argv[2];
  if (!src) throw new Error("Usage: tsx scripts/subset-fonts.ts <GentiumBook dir>");
  const out = join(process.cwd(), "public/fonts");
  mkdirSync(out, { recursive: true });
  const faces: string[] = [];
  for (const [weight, file] of [
    [400, "Regular"],
    [700, "Bold"],
  ] as const) {
    const ttf = readFileSync(join(src, `GentiumBook-${file}.ttf`));
    for (const [subset, ranges] of Object.entries(SUBSETS)) {
      const name = `gentium-book-${weight}-${subset}.woff2`;
      const woff2 = await subsetFont(ttf, toText(ranges), { targetFormat: "woff2" });
      writeFileSync(join(out, name), woff2);
      console.log(`${name}: ${(woff2.length / 1024).toFixed(0)} KB`);
      faces.push(`@font-face {
  font-family: "Gentium Book";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("/fonts/${name}") format("woff2");
  unicode-range: ${toUnicodeRange(ranges)};
}`);
    }
  }
  writeFileSync(join(out, "OFL.txt"), readFileSync(join(src, "OFL.txt")));
  writeFileSync(
    join(process.cwd(), "src/styles/fonts.css"),
    `/* Generated by scripts/subset-fonts.ts — Gentium Book 7 (SIL, OFL, see public/fonts/OFL.txt). */\n\n${faces.join("\n\n")}\n`,
  );
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
