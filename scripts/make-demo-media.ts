/**
 * Generates TEST media (demo-*) used to validate audio/subtitle sync while no
 * storyteller recording exists. Run once; outputs are committed:
 *
 *   media/audio/demo-<slug>-<lang>.opus|.m4a  a beep at each scene start, then silence
 *   media/vtt/demo-<slug>-<lang>.vtt          one cue per scene, text taken verbatim
 *                                              from the ontology (texteScene)
 *   media/demo-media.json                     overlay read by build-data.ts
 *
 * Nothing here is cultural content: the audio is synthetic and the cue texts
 * already exist in OntoBurkina_Contes.ttl. Requires ffmpeg and generated data.
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Recit } from "../src/data/schemas";

const ROOT = process.cwd();
const SCENE_SECONDS = 6;
const TARGETS = [{ slug: "yennenga-la-cavaliere", codeIso: "fra" }];

const recits = JSON.parse(readFileSync(join(ROOT, "src/data/generated/recits.json"), "utf8")) as Recit[];
mkdirSync(join(ROOT, "media/audio"), { recursive: true });
mkdirSync(join(ROOT, "media/vtt"), { recursive: true });

const ts = (s: number) => `00:${String(Math.floor(s / 60)).padStart(2, "0")}:${(s % 60).toFixed(3).padStart(6, "0")}`;

const overlay: Record<string, unknown> = {
  $comment: "Generated by scripts/make-demo-media.ts — synthetic test media, not recordings.",
};

for (const { slug, codeIso } of TARGETS) {
  const recit = recits.find((r) => r.slug === slug);
  const version = recit?.versions.find((v) => v.codeIso === codeIso);
  if (!recit || !version || version.scenes.length === 0) throw new Error(`No scenes for ${slug}/${codeIso}`);

  const base = `demo-${slug}-${codeIso}`;
  const duration = version.scenes.length * SCENE_SECONDS;
  const beep = `if(lt(mod(t\\,${SCENE_SECONDS})\\,0.35)\\,0.35*sin(2*PI*660*t)\\,0)`;
  for (const [ext, codec] of [
    ["opus", ["-c:a", "libopus", "-b:a", "64k"]],
    ["m4a", ["-c:a", "aac", "-b:a", "64k"]],
  ] as const) {
    execFileSync("ffmpeg", [
      "-y",
      "-loglevel",
      "error",
      "-f",
      "lavfi",
      "-i",
      `aevalsrc=${beep}:s=48000:d=${duration}`,
      "-ac",
      "1",
      ...codec,
      join(ROOT, `media/audio/${base}.${ext}`),
    ]);
  }

  const cues = version.scenes.map(
    (scene, i) => `${i + 1}\n${ts(i * SCENE_SECONDS)} --> ${ts((i + 1) * SCENE_SECONDS)}\n${scene.texte}\n`,
  );
  writeFileSync(join(ROOT, `media/vtt/${base}.vtt`), `WEBVTT\n\n${cues.join("\n")}`);

  overlay[`${recit.id}|${version.langueId}`] = {
    audio: `media/audio/${base}.opus`,
    audioFallback: `media/audio/${base}.m4a`,
    vtt: `media/vtt/${base}.vtt`,
    dureeSecondes: duration,
    scenes: Object.fromEntries(
      version.scenes.map((s, i) => [s.ordre, [i * SCENE_SECONDS, (i + 1) * SCENE_SECONDS]]),
    ),
  };
  console.log(`${base}: ${duration}s, ${cues.length} cues`);
}

writeFileSync(join(ROOT, "media/demo-media.json"), `${JSON.stringify(overlay, null, 2)}\n`);
